# ---------------------------------------------------------------------------
# Walls [G p.70 3.1–3.2]
# ---------------------------------------------------------------------------

def wall_area(cc_length: float, col_width: float, floor_to_floor: float,
              beam_depth: float, openings: float = 0.0) -> float:
    """Masonry / plaster area of one wall span: length centre-to-centre of
    columns less the column width, times floor-to-floor less the beam depth
    above, less the openings."""
    return max(0.0, (cc_length - col_width) * (floor_to_floor - beam_depth)
               - openings)


