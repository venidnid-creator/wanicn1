STEEL_ROOF_WASTE = {"gable": 3.0, "shed": 3.0, "truss": 3.0, "hip": 5.0}
STEEL_BAR_LENGTH = 6.0


def steel_pieces(length_m: float, roof: str) -> tuple[float, int]:
    """``(length with waste, pieces of 6 m)`` — the remainder rounds up to a
    whole piece [G p.67 6.3]."""
    w = STEEL_ROOF_WASTE.get(roof, 3.0)
    total = length_m * (1 + w / 100)
    return total, int(math.ceil(total / STEEL_BAR_LENGTH - 1e-9))


#: Roofing waste: 3% gable/shed, 5% hip [G p.69 1.1].
