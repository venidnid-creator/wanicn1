_BAR = re.compile(r"^\s*(?:(\d+)\s*[-x×]\s*)?(RB|DB)\s*(\d+)\s*(?:@\s*([\d.]+))?\s*$",
                  re.I)


def parse_bar(spec: str):
    """``"4-DB12"`` → (4, "DB12", None); ``"RB6@0.15"`` → (None, "RB6",
    0.15). None when it is not a bar."""
    m = _BAR.match(spec or "")
    if not m:
        return None
    n = int(m.group(1)) if m.group(1) else None
    size = f"{m.group(2).upper()}{int(m.group(3))}"
    if size not in REBAR_KG_M:
        return None
    sp = float(m.group(4)) if m.group(4) else None
    return n, size, sp


def bar_count(span: float, spacing: float) -> int:
    """Bars at ``spacing`` across ``span`` (both ends included)."""
    if spacing <= 0:
        return 0
    return int(math.floor(span / spacing + 1e-9)) + 1


def rebar_labour_key(size: str) -> str:
    """ว480 item 1.10 by diameter."""
    d = int(re.sub(r"\D", "", size) or 0)
    if d < 10:
        return "1.10.1"
    if d <= 16:
        return "1.10.2"
    return "1.10.3"


