#: งานขุดดินลึกไม่เกิน 2 ม.: เผื่อร้อยละ 30.
EXCAVATION_WASTE = 30.0
#: งานขุดดินลึกเกิน 2 ม.: เผื่อด้านข้างทุกด้าน 0.50 ม. (ไม่เผื่อร้อยละ).
EXCAVATION_DEEP = 2.0
EXCAVATION_SIDE = 0.50

#: วัสดุรองพื้น/ปรับระดับ บดอัดด้วยแรงคน [G p.64 2.1 (1)].
BEDDING_WASTE = {"ทราย": 25.0, "ดิน": 30.0, "ดินลูกรัง": 35.0, "อิฐหัก": 25.0}
#: ถมบริเวณ บดอัดด้วยเครื่องจักร [G p.64–65 2.1 (2)].
FILL_WASTE = {"ทราย": 40.0, "ดิน": 60.0, "ดินลูกรัง": 60.0, "อิฐหัก": 50.0}


def excavation(w: float, l: float, depth: float) -> tuple[float, float, str]:
    """``(net, total, basis)`` of one footing pit, m³.

    ``depth`` runs from the ground to the underside of the footing (≤ 2 m)
    or to the underside of the bedding (> 2 m) [G p.64]."""
    if depth <= EXCAVATION_DEEP:
        net = w * l * depth
        return net, net * (1 + EXCAVATION_WASTE / 100), \
            f"กว้าง×ยาว×ลึก เผื่อ {EXCAVATION_WASTE:g}%"
    side = 2 * EXCAVATION_SIDE
    net = (w + side) * (l + side) * depth
    return net, net, f"เผื่อด้านข้าง {EXCAVATION_SIDE:.2f} ม. (ลึกเกิน 2 ม.)"


