def q2(v: float) -> float:
    """A quantity as the forms print it: 2 decimals, half up."""
    # 1e-9 absorbs binary noise (1.005 is stored as 1.00499999…).
    return math.floor(abs(float(v)) * 100 + 0.5 + 1e-9) / 100 * \
        (1 if v >= 0 else -1)


