"""Regenerate the automatic parts of the «venit-supply» skill and package it.

    python3 venitsupply/tools/build_skill.py            # update .claude/skills/venit-supply/SKILL.md
    python3 venitsupply/tools/build_skill.py --zip DIR  # … and write DIR/venit-supply-skill.zip
    python3 venitsupply/tools/build_skill.py --check    # exit 1 when SKILL.md is out of date

Fills the blocks between ``<!-- AUTO:name -->`` and ``<!-- /AUTO:name -->``: version, builds, modules,
data, tests and release notes. Hand-written text outside the blocks is never touched. Runs from the Stop hook in
.claude/settings.json and in CI, so the skill follows every update automatically.
"""
from __future__ import annotations

import ast
import csv
import re
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]          # the repository
APP = ROOT / "venitsupply"
SKILL = ROOT / ".claude" / "skills" / "venit-supply"
SKILL_MD = SKILL / "SKILL.md"


def _doc(path: Path) -> tuple[str, list[str]]:
    """First line of the module docstring and its public top-level names."""
    try:
        tree = ast.parse(path.read_text(encoding="utf-8"))
    except (SyntaxError, UnicodeDecodeError):
        return "", []
    doc = (ast.get_docstring(tree) or "").strip().split("\n")[0]
    names = []
    for node in tree.body:
        if isinstance(node, ast.ClassDef) and not node.name.startswith("_"):
            meths = [n.name for n in node.body if isinstance(n, ast.FunctionDef) and not n.name.startswith("_")]
            names.append(f"{node.name}({len(meths)})" if meths else node.name)
        elif isinstance(node, ast.FunctionDef) and not node.name.startswith("_"):
            names.append(node.name)
    return doc, names


def block_version() -> str:
    text = (APP / "venitsupply" / "__init__.py").read_text(encoding="utf-8")
    ver = re.search(r'__version__ = "([^"]+)"', text).group(1)
    return (f"**Current version: {ver}** · generated by `venitsupply/tools/build_skill.py` from the repository "
            "— do not edit the AUTO blocks by hand.")


def block_builds() -> str:
    rows = []
    hand = (APP / "HANDOFF.md").read_text(encoding="utf-8")
    for m in re.finditer(r"(\d{4}\.\d{1,2}\.\d{1,2}\.\d+)[^\n]*?run (\d+), artifact (\d+)", hand):
        rows.append((m.group(1), m.group(2), m.group(3)))
    for m in re.finditer(r"run (\d+), artifact (\d+)\s*\n\s*`venitsupply-setup-([\d.]+)`", hand):
        rows.append((m.group(3), m.group(1), m.group(2)))
    seen, out = set(), []
    for ver, run, art in rows:
        if run in seen:
            continue
        seen.add(run)
        out.append(f"| {ver} | https://github.com/venidnid-creator/wanicn1/actions/runs/{run}/artifacts/{art} |")
    if not out:
        return "_No installer builds recorded in HANDOFF.md yet._"
    return "Installer builds (test artifacts, not released):\n\n| Version | Download (sign in to GitHub) |\n|---|---|\n" \
        + "\n".join(sorted(out))


def block_modules() -> str:
    lines = ["| File | Lines | Purpose | Public names (methods) |", "|---|---:|---|---|"]
    files = sorted((APP / "venitsupply").glob("*.py")) + [APP / "main.py"] + sorted((APP / "tools").glob("*.py"))
    for p in files:
        doc, names = _doc(p)
        n = sum(1 for _ in p.open(encoding="utf-8"))
        rel = p.relative_to(ROOT).as_posix()
        lines.append(f"| `{rel}` | {n} | {doc.replace('|', '/')} | {', '.join(names[:12])} |")
    other = ["packaging/venitsupply.spec", "installer/venitsupply.iss", "installer/release-notes.md",
             "requirements.txt", "HANDOFF.md"]
    lines.append("")
    lines.append("Other files: " + ", ".join(f"`venitsupply/{o}`" for o in other)
                 + ", `.github/workflows/venitsupply-windows.yml`, assets in `venitsupply/assets/`.")
    return "\n".join(lines)


def block_data() -> str:
    out = ["Bundled ordinance tables (`venitsupply/venitsupply/data/`):", "",
           "| File | Rows | Year | Total (บาท) | With คำชี้แจง |", "|---|---:|---:|---:|---:|"]
    for p in sorted((APP / "venitsupply" / "data").glob("*.csv")):
        rows = list(csv.reader(p.open(encoding="utf-8-sig")))
        head = rows[0]
        est = [(i, int(m.group(1))) for i, h in enumerate(head) for m in [re.match(r"ประมาณการ\s*(25\d\d)", h)] if m]
        col, fy = max(est, key=lambda c: c[1]) if est else (None, "")
        total = sum(float(r[col] or 0) for r in rows[1:] if col is not None and len(r) > col)
        di = head.index("คำชี้แจง") if "คำชี้แจง" in head else None
        det = sum(1 for r in rows[1:] if di is not None and len(r) > di and r[di])
        out.append(f"| `{p.name}` | {len(rows) - 1} | {fy} | {total:,.2f} | {det} |")
    return "\n".join(out)


def block_tests() -> str:
    out = ["Tests (`venitsupply/tests/`):", ""]
    count = 0
    for p in sorted((APP / "tests").glob("test_*.py")):
        tree = ast.parse(p.read_text(encoding="utf-8"))
        for node in tree.body:
            if isinstance(node, ast.FunctionDef) and node.name.startswith("test_"):
                count += 1
                doc = (ast.get_docstring(node) or "").split("\n")[0]
                out.append(f"- `{p.name}::{node.name}`" + (f" — {doc}" if doc else ""))
    out.insert(1, f"{count} tests.")
    return "\n".join(out)


def block_history() -> str:
    """Release notes only — a commit log would always be one commit behind the commit that adds it
    (read it with: git log -- venitsupply)."""
    notes = (APP / "installer" / "release-notes.md").read_text(encoding="utf-8").strip()
    return ("## 7. Release notes (venitsupply/installer/release-notes.md)\n\n"
            "Commit history: `git log --date=short --format='%ad %h %s' -- venitsupply .claude/skills/venit-supply`"
            "\n\n" + notes)


BLOCKS = {"version": block_version, "builds": block_builds, "modules": block_modules, "data": block_data,
          "tests": block_tests, "history": block_history}


def render(text: str) -> str:
    for name, fn in BLOCKS.items():
        pat = re.compile(rf"(<!-- AUTO:{name} -->)(.*?)(<!-- /AUTO:{name} -->)", re.S)
        text = pat.sub(lambda m: f"{m.group(1)}\n{fn()}\n{m.group(3)}", text)
    return text


def package(dest: Path) -> Path:
    dest.mkdir(parents=True, exist_ok=True)
    out = dest / "venit-supply-skill.zip"
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        for p in sorted(SKILL.rglob("*")):
            if p.is_file():
                z.write(p, Path("venit-supply") / p.relative_to(SKILL))
    return out


def main(argv: list[str]) -> int:
    old = SKILL_MD.read_text(encoding="utf-8")
    new = render(old)
    if "--check" in argv:
        if new != old:
            print("SKILL.md is out of date — run venitsupply/tools/build_skill.py")
            return 1
        return 0
    if new != old:
        SKILL_MD.write_text(new, encoding="utf-8")
    if "--zip" in argv:
        i = argv.index("--zip")
        dest = Path(argv[i + 1]) if len(argv) > i + 1 else APP / "dist"
        z = package(dest)
        if "--quiet" not in argv:
            print(f"packaged {z}")
    if "--quiet" not in argv:
        print("SKILL.md updated" if new != old else "SKILL.md already current")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
